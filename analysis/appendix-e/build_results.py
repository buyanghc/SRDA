"""Validate episode evidence against Table 3 and export Appendix E tables."""
import csv
import hashlib
import json
from collections import defaultdict
from pathlib import Path

ROOT=Path(__file__).resolve().parent
TABLES=ROOT.parents[1]/'paper/tables'
COUNTS=ROOT.parent/'realistic-workflows/counts.csv'
CONDITIONS=['system-terminal','forward-terminal','system-natural','forward-natural']
NAMES=['Baseline','Guidance','Natural feedback','Both']
TOPOLOGIES=['single-route','recoverable-branch','redundant-route']
SHORT=['Single','Branch','Redundant']

def write_table(name,caption,label,columns,header,rows,size='small'):
    # Flow through the appendix; repeat headers rather than create float-only pages.
    text=[r'% Generated by analysis/appendix-e/build_results.py.',r'\begingroup', '\\'+size,r'\setlength{\tabcolsep}{5pt}',r'\setlength{\LTcapwidth}{\linewidth}',r'\renewcommand{\arraystretch}{1.04}',r'\begin{longtable}{@{}'+columns+r'@{}}',r'\caption{'+caption+r'}\label{'+label+r'}\\',r'\toprule',header,r'\midrule',r'\endfirsthead',r'\multicolumn{'+str(len(columns))+r'}{c}{Table \thetable{} (continued)}\\',r'\toprule',header,r'\midrule',r'\endhead',r'\bottomrule',r'\endfoot',*rows,r'\end{longtable}',r'\endgroup']
    (TABLES/(name+'.tex')).write_text('\n'.join(text)+'\n')

def main():
    counts=list(csv.DictReader(COUNTS.open()))
    models=list(dict.fromkeys(x['model'] for x in counts))
    source_models={x['source_path']:x['model'] for x in counts}
    cells=defaultdict(list); graphs={}; tasks={}; keys=set(); sources=[]
    release=ROOT.parents[1]
    index=json.loads((release/'results/workflows/index.json').read_text())
    released_runs=[]
    for cell in index['cells']:
        eps=[]
        for part in cell['parts']:eps.extend(json.loads(x) for x in (release/part['path']).read_text().splitlines())
        cfg=json.loads((release/'experiments/workflows/configs'/cell['model']/(cell['condition']+'.json')).read_text())
        released_runs.append(dict(source={'path':'workflows/'+cell['model']+'/'+cell['condition']},config={'formal_config':cfg},episodes=eps))
    for run in released_runs:
        src=run['source']; model=source_models[src['path']]
        cfg=run['config']['formal_config']; guidance=cfg['experiment']['attack_task_carried_routing_policy']!='none'
        assert cfg['budget']=={'max_messages_per_request':64,'max_runtime_seconds_per_request':180}
        assert cfg['experiment']['repetitions']==3
        assert cfg['experiment']['legitimate_task_carried_routing_policy']=='none'
        for r in run['episodes']:
            assert r['status']=='COMPLETED' and r['condition']=='normal_plus_attack'
            c=('forward' if guidance else 'system')+('-natural' if r['regime']=='natural_feedback' else '-terminal')
            rep=r['report']; key=(model,c,r['graph_id'],r['normal_pair_id'],r['attack_pair_id'],r['repetition_id'])
            assert key not in keys; keys.add(key)
            assert rep['joint_success']==(rep['attack_success'] and rep['benign_workflow_success'])
            assert rep['shared_environment'] and rep['execution_mode']=='concurrent_requests_shared_environment'
            graph=rep['workflow_graph']
            if r['graph_id'] in graphs: assert graphs[r['graph_id']]==graph
            graphs[r['graph_id']]=graph
            for kind in ['normal','attack']:
                sub=rep[kind+'_request_report']
                assert not sub['infrastructure_error']
                assert sub['budget']['max_messages']==64 and sub['budget']['max_runtime_seconds']==180
                assert sub['budget']['max_tool_iterations']==4
                t=sub['target']; task_id=rep[kind+'_case']['target_instance_id']
                if task_id in tasks: assert tasks[task_id]==t
                tasks[task_id]=t
            cells[(model,c)].append(r)
    assert len(keys)==1296 and len(cells)==24
    for x in counts:
        rows=cells[(x['model'],x['condition'])]
        assert len(rows)==int(x['n'])==54
        for column,flag in [('attack_successes','attack_success'),('benign_successes','benign_workflow_success'),('joint_successes','joint_success')]:
            assert sum(r['report'][flag] for r in rows)==int(x[column]),(x['model'],x['condition'],column)
    detailed=[]
    for domain in ['workspace','banking']:
        rows=[]
        for mi,model in enumerate(models):
            if mi: rows.append(r'\addlinespace[3pt]')
            for i,topo in enumerate(TOPOLOGIES):
                values=[]
                for c in CONDITIONS:
                    rr=[r for r in cells[(model,c)] if r['graph_id']==domain+'-'+topo]
                    assert len(rr)==9
                    a=sum(r['report']['attack_success'] for r in rr); b=sum(r['report']['benign_workflow_success'] for r in rr)
                    values.extend([str(a),str(b)])
                    detailed.append(dict(model=model,domain=domain,topology=topo,condition=c,n=9,attack=a,benign=b))
                rows.append(' & '.join([model if i==0 else '',SHORT[i]]+values)+(r' \\*' if i<2 else r' \\'))
        header=r'& & \multicolumn{2}{c}{Baseline} & \multicolumn{2}{c}{Guidance} & \multicolumn{2}{c}{Natural feedback} & \multicolumn{2}{c}{Both} \\'+'\n'+r'\cmidrule(lr){3-4}\cmidrule(lr){5-6}\cmidrule(lr){7-8}\cmidrule(lr){9-10}'+'\n'+r'Model & Topology & A & B & A & B & A & B & A & B \\'
        write_table('appendix-'+domain+'-outcomes',domain.title()+r' workflow outcomes. A: attack successes; B: benign completions. Each pair of counts is out of nine executions (three task pairs $\times$ three repetitions).','tab:'+domain+'-outcomes','llrrrrrrrr',header,rows)
    rows=[]; joint=[]
    for mi,model in enumerate(models):
        if mi: rows.append(r'\addlinespace[3pt]')
        for ci,c in enumerate(CONDITIONS):
            rr=cells[(model,c)]; a=sum(r['report']['attack_success'] for r in rr); b=sum(r['report']['benign_workflow_success'] for r in rr); j=sum(r['report']['joint_success'] for r in rr)
            vals=[j,a-j,b-j,54-a-b+j]
            rows.append(' & '.join([model if ci==0 else '',NAMES[ci]]+list(map(str,vals)))+(r' \\*' if ci<3 else r' \\'))
            joint.append(dict(model=model,condition=c,both=vals[0],attack_only=vals[1],benign_only=vals[2],neither=vals[3]))
    write_table('appendix-workflow-joint','Joint workflow outcomes during execution. The four mutually exclusive counts sum to 54 per model and condition.','tab:workflow-joint','llrrrr',r'Model & Condition & Both succeed & Attack only & Benign only & Neither \\',rows)
    for filename,values in [('detailed-counts.csv',detailed),('joint-counts.csv',joint)]:
        with (ROOT/filename).open('w') as f:
            w=csv.DictWriter(f,fieldnames=values[0].keys());w.writeheader();w.writerows(values)
    audit={'unique_executions':len(keys),'model_condition_cells':len(cells),'all_table3_counts_match':True,'all_statuses_completed':True,'infrastructure_errors':0,'sources':sources,'graphs':graphs,'tasks':tasks}
    (ROOT/'validation.json').write_text(json.dumps(audit,indent=2)+'\n')
    print(json.dumps({k:v for k,v in audit.items() if k not in ['graphs','tasks','sources']},indent=2))
    print('Both joint counts:',[(x['model'],x['both']) for x in joint if x['condition']=='forward-natural'])

if __name__=='__main__': main()
