"""Derive Appendix D from the frozen six-configuration controlled cohort.

No experiment writes. P90 uses linear interpolation at (n-1)*0.9.
Seed ranges are observed min/max, not confidence intervals.
"""
import csv
import gzip
import hashlib
import json
import statistics as st
import tarfile
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = Path(__file__).resolve().parent
TABLES = ROOT / 'paper/tables'
CONDITIONS = [f'{h}-{f}' for h in ('system', 'forward') for f in ('terminal', 'empty', 'natural')]
NAMES = {
    'qwen3-14b': 'Qwen3-14B',
    'qwen3.5-9B-nothinking': 'Qwen3.5-9B (no-thinking)',
    'qwen3.5-9B-thinking': 'Qwen3.5-9B (thinking)',
    'ministral3-14b': 'Ministral-3-14B-Instruct',
    'gpt-oss-20b-low': 'GPT-OSS-20B',
    'llama3.1-8b': 'Llama-3.1-8B',
}
MODELS = list(NAMES)

def read(p):
    with (gzip.open(p,'rt',newline='') if p.suffix=='.gz' else p.open(newline='')) as f:
        return list(csv.DictReader(f))

def save_csv(name, rows):
    with (OUT / name).open('w', newline='') as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)

def asr(rows):
    return 100 * sum(r['attack_success'] == 'True' for r in rows) / len(rows)

def effects(a):
    return [a[3]-a[0], a[1]-a[0], a[2]-a[0], a[4]-a[3]-a[1]+a[0], a[5]-a[3]-a[2]+a[0]]

def quantile(v, p):
    v = sorted(v)
    x = (len(v)-1)*p
    i = int(x)
    return v[i] + (v[min(i+1,len(v)-1)]-v[i])*(x-i)

def row(cells):
    return ' & '.join(str(c) for c in cells) + r' \\'

def table(name, caption, label, spec, lines):
    cut=lines.index(r'\midrule')+1
    header,body=lines[:cut],lines[cut:]
    text = '\n'.join([
        '% Generated by analysis/appendix-d/build_results.py.',
        r'\begingroup\small', r'\setlength{\tabcolsep}{4pt}',
        r'\setlength{\LTcapwidth}{\linewidth}',
        r'\begin{longtable}{@{}' + spec + '@{}}',
        r'\caption{' + caption + '}'+r'\label{' + label + r'}\\',
        r'\toprule',*header,r'\endfirsthead',
        r'\caption[]{'+caption.split('. ')[0]+r' (continued).}\\',
        r'\toprule',*header,r'\endhead',
        r'\midrule\endfoot',r'\bottomrule\endlastfoot',
        *body, r'\end{longtable}', r'\endgroup', ''])
    (TABLES / name).write_text(text)

sources = json.loads((ROOT/'analysis/cost/audit.json').read_text())['sources']
ledger = {(r['campaign'],r['condition']):r for r in read(ROOT/'analysis/combined-effects/source_data.csv')}
topology_ref = {(r['campaign'],r['condition'],r['graph']):r for r in read(ROOT/'analysis/topology-effects/by_model_topology_condition.csv')}
episode_ref = {(r['campaign'],r['condition'],r['episode_key']):r for r in read(ROOT/'analysis/main-asr/episode-outcomes.csv') if r['campaign'] in NAMES}
graphs = [r['graph'] for r in read(ROOT/'analysis/topology-effects/topology_structure.csv')]
raw = {}
manifest=[]
for s in sources:
    p=ROOT / s['source']; m,c=s['campaign'],s['condition']
    digest=hashlib.sha256(p.read_bytes()).hexdigest()
    assert digest == s['sha256']
    rows=read(p); keys={r['episode_key'] for r in rows}
    assert len(rows)==len(keys)==1890
    assert sum(r['attack_success']=='True' for r in rows)==int(ledger[m,c]['successes'])
    assert sum(r['status']=='ERROR' for r in rows)==int(ledger[m,c]['errors'])
    for r in rows:
        if (m,c,r['episode_key']) in episode_ref:
            assert int(r['attack_success']=='True')==int(episode_ref[m,c,r['episode_key']]['success'])
        assert (int(r['graph_seed']), int(r['role_seed']))== (int(r['repetition_id']),100+int(r['repetition_id']))
    config=json.loads(gzip.decompress((p.parent.parent/'config.json.gz').read_bytes()))
    assert config['budget']==dict(max_messages=16,max_runtime_seconds=90.0,max_tool_iterations=4)
    raw[m,c]=rows
    manifest.append(dict(campaign=m,condition=c,source=str(p),sha256=digest,n=len(rows)))
assert len(raw)==36 and len(episode_ref)==68040
assert all({r['episode_key'] for r in v}==keys for v in raw.values())

topo=[]; topo_effects=[]; seed=[]; costs=[]
for m in MODELS:
    for g in graphs:
        vals=[]
        for c in CONDITIONS:
            rs=[r for r in raw[m,c] if r['graph_name']==g]
            assert len(rs)==135
            a=asr(rs); ref=topology_ref[m,c,g]
            assert abs(a-float(ref['asr_pp']))<1e-10
            topo.append(dict(campaign=m,graph=g,condition=c,n=135,successes=sum(r['attack_success']=='True' for r in rs),asr=a))
            vals.append(a)
        topo_effects.append(dict(campaign=m,graph=g,**dict(zip(['H','E','N','IxE','IxN'],effects(vals)))))
    for rep in range(3):
        vals=[]
        for c in CONDITIONS:
            rs=[r for r in raw[m,c] if int(r['repetition_id'])==rep]
            assert len(rs)==630
            vals.append(asr(rs))
        seed.append(dict(campaign=m,repetition=rep,**dict(zip(CONDITIONS,vals)),**dict(zip(['H','E','N','IxE','IxN'],effects(vals)))))
    for c in CONDITIONS:
        rs=raw[m,c]
        tok=[float(r['total_tokens']) for r in rs if r['total_tokens']]
        secs=[float(r['elapsed_seconds']) for r in rs if r['elapsed_seconds']]
        assert len(secs)==1890
        costs.append(dict(campaign=m,condition=c,n=len(rs),token_n=len(tok),token_median=st.median(tok),token_p90=quantile(tok,.9),time_median=st.median(secs),time_p90=quantile(secs,.9),errors=sum(r['status']=='ERROR' for r in rs),message_limit=sum(r['message_budget_exhausted']=='True' for r in rs),time_limit=sum(r['runtime_budget_exhausted']=='True' for r in rs),either_limit=sum(r['message_budget_exhausted']=='True' or r['runtime_budget_exhausted']=='True' for r in rs),both_limits=sum(r['message_budget_exhausted']=='True' and r['runtime_budget_exhausted']=='True' for r in rs),success_with_limit=sum(r['attack_success']=='True' and (r['message_budget_exhausted']=='True' or r['runtime_budget_exhausted']=='True') for r in rs)))
save_csv('topology-asr.csv',topo)
save_csv('topology-effects.csv',topo_effects)
save_csv('seed-results.csv',seed)
save_csv('cost-outcomes.csv',costs)

lookup={(r['campaign'],r['graph'],r['condition']):r['asr'] for r in topo}
headers=[r'Topology',r'$-H/T$',r'$-H/E$',r'$-H/N$',r'$+H/T$',r'$+H/E$',r'$+H/N$']
for i in range(3):
    lines=[row(headers),r'\midrule']
    for m in MODELS[2*i:2*i+2]:
        lines += [r'\multicolumn{7}{l}{'+NAMES[m]+r'} \\*',r'\addlinespace']
        for g in graphs:
            name=r'\( '+g+r' \)' if g.startswith('G(') else g
            line=row([name]+[f'{lookup[m,g,c]:.2f}' for c in CONDITIONS])
            if g in (graphs[0],graphs[-2]):
                line+='*'
            lines.append(line)
        lines.append(r'\midrule')
    lines.pop()
    table(f'appendix-full-asr-{i+1}.tex',r'ASR (\%) by topology for '+NAMES[MODELS[2*i]]+' and '+NAMES[MODELS[2*i+1]]+r'. Each cell contains 135 executions. $+H/-H$ denotes guidance present/absent; T/E/N denotes Terminal/Empty/Natural feedback.',f'tab:full-asr-{i+1}','lrrrrrr',lines)

eff={(r['campaign'],r['graph']):r for r in topo_effects}
contrasts=[]
for m in MODELS:
    contrasts.append(dict(campaign=m,depth=eff[m,'G(1,6)']['H']-eff[m,'G(1,2)']['H'],branch_H=eff[m,'G(3,3)']['H']-eff[m,'G(1,3)']['H'],branch_I=eff[m,'G(3,3)']['IxN']-eff[m,'G(1,3)']['IxN'],one_link_H=eff[m,'G33-P2']['H']-eff[m,'G33-X2']['H'],two_link_H=eff[m,'G33-P3']['H']-eff[m,'G33-X3']['H']))
save_csv('topology-contrasts.csv',contrasts)
table('appendix-topology-contrasts.tex',r'Within-model topology contrasts in effect size (percentage points). Depth compares $G(1,6)-G(1,2)$; branching compares $G(3,3)-G(1,3)$; link contrasts compare target-reaching minus matched dead-end additions.', 'tab:topology-contrasts','lrrrrr',[
row(['Model','Depth',r'\multicolumn{2}{c}{Branching}',r'\multicolumn{2}{c}{Added links: $\Delta_h^{\mathrm T}$}']),r'\cmidrule(lr){3-4}\cmidrule(l){5-6}',row(['',r'$\Delta_h^{\mathrm T}$',r'$\Delta_h^{\mathrm T}$',r'$I_{\mathrm N}$','1-link','2-link']),r'\midrule',
*[row([NAMES[r['campaign']]]+[f'{r[k]:+.2f}' for k in ['depth','branch_H','branch_I','one_link_H','two_link_H']]) for r in contrasts]])
lines=[row(['Model',r'$\Delta_h^{\mathrm T}$',r'$\Delta_{\mathrm E}^{0}$',r'$\Delta_{\mathrm N}^{0}$',r'$I_{\mathrm E}$',r'$I_{\mathrm N}$']),r'\midrule']
for m in MODELS:
    rs=[r for r in seed if r['campaign']==m]
    lines.append(row([NAMES[m]]+[r'$['+f"{min(r[k] for r in rs):.2f},{max(r[k] for r in rs):.2f}"+']$' for k in ['H','E','N','IxE','IxN']]))
table('appendix-seed-ranges.tex',r'Observed effect ranges across the three paired graph/role seeds (percentage points), with 630 executions per condition and seed pair.','tab:seed-ranges','lrrrrr',lines)

for i in range(2):
    lines=[row(['Condition',r'\multicolumn{2}{c}{Tokens (thousands)}',r'\multicolumn{2}{c}{Time (s)}',r'\multicolumn{3}{c}{Execution counts}']),r'\cmidrule(lr){2-3}\cmidrule(lr){4-5}\cmidrule(l){6-8}',row(['','Median','P90','Median','P90','Error','Msg. limit','Time limit']),r'\midrule']
    for m in MODELS[3*i:3*i+3]:
        lines += [r'\multicolumn{8}{l}{'+NAMES[m]+r'} \\*',r'\addlinespace']
        for r in [r for r in costs if r['campaign']==m]:
            c=CONDITIONS.index(r['condition']); cond=['$-H/T$','$-H/E$','$-H/N$','$+H/T$','$+H/E$','$+H/N$'][c]
            line=row([cond,f"{r['token_median']/1000:.2f}",f"{r['token_p90']/1000:.2f}",f"{r['time_median']:.2f}",f"{r['time_p90']:.2f}",r['errors'],r['message_limit'],r['time_limit']])
            if c<5:
                line+='*'
            lines.append(line)
        lines.append(r'\midrule')
    lines.pop()
    table(f'appendix-cost-outcomes-{i+1}.tex',r'Full-execution cost distributions and recorded error/budget events. Each row has 1,890 executions; P90 is the 90th percentile. Budget flags are counted independently of verified success.','tab:cost-outcomes-'+str(i+1),'lrrrrrrr',lines)

audit=dict(source_status='ACTUAL_RUN',scope='Existing six-configuration manuscript cohort; no new exclusions or experiment changes',episodes=68040,sources=manifest,all_source_hashes_match=True,historical_episode_labels_checked=68040,all_topology_cells_match=True,quantile='Linear interpolation at (n-1)p',seed_ranges='Observed min/max across three paired graph/role seeds; not confidence intervals',termination_counts=dict(Counter(r['termination_reason'] for rs in raw.values() for r in rs)),totals={k:sum(r[k] for r in costs) for k in ['errors','message_limit','time_limit','either_limit','both_limits','success_with_limit']})
(OUT/'audit.json').write_text(json.dumps(audit,indent=2)+'\n')

trace_manifest=json.loads((OUT/'trace-manifest.json').read_text())
recovery=json.loads((OUT/'trace-recovery.json').read_text())['report']
unsuccessful=json.loads((OUT/'trace-unsuccessful.json').read_text())['report']
assert recovery['assigned_team']==unsuccessful['assigned_team']
assert recovery['target']==unsuccessful['target']
assert not unsuccessful['target_agent_reached']
assert not unsuccessful['runtime_budget_exhausted'] and not unsuccessful['message_budget_exhausted']
print(json.dumps(dict(episodes=68040,topology_cells=len(topo),cost_cells=len(costs),totals=audit['totals'],traces=trace_manifest),indent=2))
